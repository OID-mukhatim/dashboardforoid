/** الوصول لنص الواجهة عبر مسار مثل "kpis.title". */
export const t = (lang: Lang, path: string): string => {
  const keys = path.split(".");
  let result: unknown = UI_STRINGS[lang];
  for (const key of keys) {
    result = (result as Record<string, unknown> | undefined)?.[key];
    if (result === undefined) return path;
  }
  return typeof result === "string" ? result : path;
};

/** نص الواجهة مع استبدال متغيرات مثل {count}. */
export const tFormat = (
  lang: Lang,
  path: string,
  vars: Record<string, string | number>,
): string => {
  let text = t(lang, path);
  Object.entries(vars).forEach(([key, val]) => {
    text = text.replace(`{${key}}`, String(val));
  });
  return text;
};
